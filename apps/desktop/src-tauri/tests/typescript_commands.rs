fn render(entries: &[Entry]) -> String {
    let imports: BTreeSet<&str> = entries
        .iter()
        .flat_map(|e| e.imports.iter().map(String::as_str))
        .collect();
    let mut sorted: Vec<&Entry> = entries.iter().collect();
    sorted.sort_by_key(|e| e.method);

    let mut out = String::from(
        "// Generated by apps/desktop/src-tauri/tests/typescript_commands.rs from formation-proto.\n\
         // Do not edit; run `pnpm -C apps/desktop ipc:generate`.\n\n",
    );
    for name in imports {
        out.push_str(&format!("import type {{ {name} }} from \"./{name}\";\n"));
    }
    out.push_str(
        "\n/** Every JSON-RPC method on formationd's local socket, with its params and result. */\n\
         export type Commands = {\n",
    );
    for e in sorted {
        out.push_str(&format!(
            "  {}: {{ params: {}; result: {} }};\n",
            e.method, e.params, e.result
        ));
    }
    out.push_str(&format!(
        "}};\n\n\
         export type Method = keyof Commands;\n\
         export type Params<M extends Method> = Commands[M][\"params\"];\n\
         export type Result<M extends Method> = Commands[M][\"result\"];\n\n\
         /** The JSON-RPC notification whose params is an `EventEnvelope`. */\n\
         export const EVENT_NOTIFICATION = \"{EVENT_NOTIFICATION}\";\n\n\
         /** The contract version the app was built with; compare with `Snapshot.daemon.protocol`. */\n\
         export const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n",
        PROTOCOL_VERSION = snapshot::PROTOCOL_VERSION
    ));
    out
}

#[test]
fn every_socket_method_is_in_the_map() {
    let cfg = Config::from_env();
    let mapped: BTreeSet<&str> = commands(&cfg).iter().map(|e| e.method).collect();
    let all: BTreeSet<&str> = formation_proto::methods().collect();
    let missing: Vec<&&str> = all.difference(&mapped).collect();
    assert!(
        missing.is_empty(),
        "add these methods to commands() in tests/typescript_commands.rs: {missing:?}"
    );
    assert_eq!(
        mapped.len(),
        commands(&cfg).len(),
        "a method is listed twice"
    );
}

#[test]
fn export_commands_ts() {
    let cfg = Config::from_env();
    let dir: PathBuf = std::env::var_os("TS_RS_EXPORT_DIR")
        .map(PathBuf::from)
        .expect("TS_RS_EXPORT_DIR is set by .cargo/config.toml");
    fs::create_dir_all(&dir).expect("create the export directory");
    fs::write(dir.join("commands.ts"), render(&commands(&cfg))).expect("write commands.ts");
}
