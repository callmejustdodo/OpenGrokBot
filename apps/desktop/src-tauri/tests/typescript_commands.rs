//! Generates `apps/desktop/src/ipc/generated/commands.ts`: every JSON-RPC method
//! on formationd's local socket, mapped to its params and result types. ts-rs
//! generates the types themselves (`cargo test -p formation-proto`); this adds
//! the method map that the Rust `Command` trait holds, so the UI can call
//! `call("agent_start", params)` with checked params and result.
//!
//! The test fails when a method exists in `formation_proto::methods()` but not
//! in `commands()` below, so a new command cannot be left out of the map.

use std::collections::BTreeSet;
use std::fs;
use std::path::PathBuf;

use formation_proto::common::{Command, EVENT_NOTIFICATION};
use formation_proto::{agent, ask, harness, peer, policy, request, snapshot, team};
use ts_rs::{Config, Dependency, TS, TypeVisitor};

/// One method: its name, params and result in TypeScript, and the names to import.
struct Entry {
    method: &'static str,
    params: String,
    result: String,
    imports: Vec<String>,
}

/// Collects the exported types a type name refers to at its top level: the type
/// itself if it is exported (`Agent`), otherwise its type arguments
/// (`Vec<Activity>` refers to `Activity`, `()` to nothing).
struct Referenced<'a> {
    cfg: &'a Config,
    names: Vec<String>,
}

impl TypeVisitor for Referenced<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if let Some(dep) = Dependency::from_ty::<T>(self.cfg) {
            self.names.push(dep.ts_name);
        }
    }
}

fn referenced<T: TS + 'static>(cfg: &Config) -> Vec<String> {
    let mut v = Referenced {
        cfg,
        names: Vec::new(),
    };
    v.visit::<T>();
    T::visit_generics(&mut v);
    v.names
}

fn entry<C>(cfg: &Config) -> Entry
where
    C: Command + TS + 'static,
    C::Output: TS + 'static,
{
    let mut imports = referenced::<C>(cfg);
    imports.extend(referenced::<C::Output>(cfg));
    Entry {
        method: C::METHOD,
        params: C::name(cfg),
        result: C::Output::name(cfg),
        imports,
    }
}

