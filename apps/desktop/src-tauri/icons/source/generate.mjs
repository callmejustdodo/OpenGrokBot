// Writes the icon sources (app-icon.svg, tray-icon.svg) from the agent avatar
// shapes the app and the README header use (src/components/sidebar/avatarShapes.ts,
// open-bot-avatar, MIT). Run from anywhere: `node apps/desktop/src-tauri/icons/source/generate.mjs`.
// Then render the PNG, ICNS and ICO files as icons/README.md describes.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const shapesSource = readFileSync(join(here, "../../../src/components/sidebar/avatarShapes.ts"), "utf8");
const shapes = JSON.parse(shapesSource.match(/BOT_SHAPES: Record<string, BotShape> = (\{.*\});/s)[1]);

// The demo's first four agents, in the README header's colors.
const team = [
  { shape: "rocket", color: "#3a6df0" },
  { shape: "star", color: "#ff6a1a" },
  { shape: "magnifier", color: "#8a5cf0" },
  { shape: "cat", color: "#f8a01c" },
];

// Eyes as AgentAvatar.tsx draws them: two rounded bars, centered on [x, y].
function eyes([x, y, spacing, scale]) {
  const w = 4 * scale * 1.25;
  const h = 11 * scale * 1.25;
  return [x - spacing / 2, x + spacing / 2].map(
    (cx) => `<rect x="${cx - w / 2}" y="${y - h / 2}" width="${w}" height="${h}" rx="${w / 2}"/>`,
  );
}

function bot({ shape, color }, x, y, size) {
  const s = shapes[shape];
  return `<g transform="translate(${x} ${y}) scale(${size / 100})"><path d="${s.p}" fill="${color}"/><g fill="#151515">${eyes(s.e).join("")}</g></g>`;
}

// App icon: the four agents in a 2 × 2 team on the v2 "Sky Glass" backdrop,
// on the macOS icon grid (an 824 px rounded square in a 1024 px canvas).
const cell = 360;
const origin = 512 - cell;
const appIcon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <!-- Generated by generate.mjs; edit that file, not this one. -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#f3f7fd"/>
      <stop offset="1" stop-color="#d7e5fb"/>
    </linearGradient>
  </defs>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#bg)"/>
  <rect x="101" y="101" width="822" height="822" rx="184" fill="none" stroke="#ffffff" stroke-opacity=".9" stroke-width="2"/>
  ${team.map((m, i) => bot(m, origin + (i % 2) * cell, origin + Math.floor(i / 2) * cell, cell)).join("\n  ")}
</svg>
`;

// Menu bar glyph: the lead agent's (rocket's) body in black with its eyes cut
// out, drawn as a template image.
const lead = shapes[team[0].shape];
const trayIcon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
  <!-- Generated by generate.mjs; edit that file, not this one. -->
  <mask id="eyes"><rect width="100" height="100" fill="#ffffff"/><g fill="#000000">${eyes(lead.e).join("")}</g></mask>
  <path d="${lead.p}" fill="#000000" mask="url(#eyes)"/>
</svg>
`;

writeFileSync(join(here, "app-icon.svg"), appIcon);
writeFileSync(join(here, "tray-icon.svg"), trayIcon);
